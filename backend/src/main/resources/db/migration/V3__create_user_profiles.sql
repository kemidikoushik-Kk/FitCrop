-- V3: Create User Profiles Table
CREATE TABLE IF NOT EXISTS user_profiles (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL UNIQUE,
    date_of_birth DATE,
    gender VARCHAR(20),
    height_cm DOUBLE,
    weight_kg DOUBLE,
    fitness_level VARCHAR(30) NOT NULL DEFAULT 'BEGINNER',
    occupation VARCHAR(100),
    working_days VARCHAR(100) DEFAULT 'MON,TUE,WED,THU,FRI',
    work_start_time TIME DEFAULT '09:00:00',
    work_end_time TIME DEFAULT '18:00:00',
    sleep_schedule VARCHAR(50) DEFAULT '23:00 - 07:00',
    preferred_workout_days VARCHAR(100) DEFAULT 'MON,WED,FRI',
    preferred_workout_time VARCHAR(50) DEFAULT 'MORNING',
    available_workout_minutes INT DEFAULT 30,
    equipment_access VARCHAR(50) DEFAULT 'NONE',
    dietary_preference VARCHAR(50) DEFAULT 'NO_PREFERENCE',
    food_allergies TEXT,
    food_dislikes TEXT,
    meal_preference VARCHAR(50) DEFAULT 'THREE_MEALS',
    primary_fitness_goal VARCHAR(50) DEFAULT 'GENERAL_FITNESS',
    secondary_goal VARCHAR(50),
    activity_level VARCHAR(50) DEFAULT 'SEDENTARY',
    timezone VARCHAR(50) DEFAULT 'Asia/Kolkata',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
